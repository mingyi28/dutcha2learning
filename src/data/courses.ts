// 根据ID获取主题
export function getThemaById(id: string): Thema | undefined {
  return themas.find(t => t.id === id);
}

// 获取所有课程（扁平化）
export function getCourses(): Course[] {
  return themas.flatMap(t => t.courses);
}

// 根据ID获取课程
export function getCourseById(id: string): Course | undefined {
  return getCourses().find(c => c.id === id);
}

// 根据课程ID获取所属主题
export function getThemaByCourseId(courseId: string): Thema | undefined {
  return themas.find(t => t.courses.some(c => c.id === courseId));
}
